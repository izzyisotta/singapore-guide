#!/usr/bin/env python3
"""Merge research/*.json (hoods, places, walks) + src/static.js + src/top.js into src/data.js."""
import json, pathlib
root = pathlib.Path(__file__).parent
cfg = json.loads((root/'research/config.json').read_text())   # home, campus, rank order, overrides
hoods, places, walks = [], [], []
for f in sorted((root/'research').glob('hoods-*.json')):
    d = json.loads(f.read_text())
    hoods += d.get('hoods', []); places += d.get('places', []); walks += d.get('walks', [])
ov = json.loads((root/'research/overrides.json').read_text())
def dropped_by(p): return any(all(p.get(k) == v for k, v in d.items() if k != 'why') for d in ov['drop'])
places = [p for p in places if not dropped_by(p)]
for p in places:
    p['n'] = ov['rename'].get(p['n'], p['n'])
    for k, v in ov['set'].get(p['n'], {}).items():
        if v is None: p.pop(k, None)
        else: p[k] = v
vf = root/'research/vibe.json'   # vibe/price/coolness pass (her correction, 22 Oct: taste = vibe, not cuisine)
if vf.exists():
    V = {r['n']: r for r in json.loads(vf.read_text()).get('rescore', [])}
    for p in places:
        r = V.get(p['n'])
        if not r: continue
        for k in ('pp', 'energy', 'cool', 'vibe', 'london'):
            if k in r: p[k] = r[k]
        if 'you' in r:
            t = [x for x in p.get('tags', []) if x != 'you']
            p['tags'] = (['you'] + t) if r['you'] else t
rank = {k: i+1 for i, k in enumerate(cfg['rank'])}
for h in hoods:
    h['rank'] = rank.get(h['k'])
    if h['k'] == 'far' or not h.get('poly'): h['far'] = True; h.pop('poly', None)
seen, keep, dropped = set(), [], []
for p in places:
    key = p['n'].strip().lower()
    if key in seen: continue
    if not p.get('at'): dropped.append(p['n']); continue
    seen.add(key); p.setdefault('tags', []); p.setdefault('p', 3); keep.append(p)
for i, w in enumerate(walks):
    w['k'] = 'w%d' % (i+1)
    w['stops'] = [s for s in w.get('stops', []) if s.strip().lower() in seen and s not in ov.get('walk_drop_stops', {}).get(w['name'], [])]
    w['pts'] = w['stops']
    w.setdefault('from', 'home')
walks = [w for w in walks if len(w['pts']) >= 2]
import re
FIX = [
 ("ten minutes' walk from her flat", "20 minutes' walk from your flat"),
 ("five minutes from her door", "a 20-minute walk from your door"),
 ("skyline view near her flat", "skyline view within a 20-minute walk of your flat"),
 ("on her own road", "on your road, at the Outram end"),
 ("Close to her flat.", "Ten minutes from your flat, under the Ridges."),
 ("(her doorstep)", "(your doorstep)"),
 ("the Ridges start near her flat", "the Ridges start at your door"),
 ("most her-shaped", "most you-shaped"), ("most 'her'", "most 'you'"),
 ("she rated", "you rated"), ("She'll", "You'll"), ("she'll", "you'll"), ("if she does one", "if you do one"), ("If she does one", "If you do one"),
 ("if she wants", "if you want"), ("if she doesn't want", "if you don't want"), ("if she's curious", "if you're curious"),
 ("she likes", "you like"), ("which she rated", "which you rated"), ("not for her", "not for you"), ("for her", "for you"),
 ("Her ", "Your "), ("her ", "your "),
]
def you(x):
    if isinstance(x, str):
        for a, b in FIX: x = re.sub(r'(?<![A-Za-z])' + re.escape(a), b, x)
        return x
    if isinstance(x, list): return [you(v) for v in x]
    if isinstance(x, dict): return {k: (v if k in ('n','h','k','t','tags','at','poly','stops','pts','tier','price') else you(v)) for k, v in x.items()}
    return x
hoods, keep, walks = you(hoods), you(keep), you(walks)
def rep(x):
    if isinstance(x, str):
        for a, b in ov['replace']: x = x.replace(a, b)
        return x
    if isinstance(x, list): return [rep(v) for v in x]
    if isinstance(x, dict): return {k: rep(v) for k, v in x.items()}
    return x
hoods, keep, walks = rep(hoods), rep(keep), rep(walks)
J = lambda o: json.dumps(o, ensure_ascii=False, indent=0)
out = f"""// ---------- Singapore guide data (generated by merge.py; edit research/*.json) ----------
const HOME = {{ name: 'Home · The Keystone, Kampong Bahru Rd', ll: {J(cfg['home'])} }};
const WHARTON = {{ name: 'INSEAD Asia campus', ll: {J(cfg['campus'])} }};
function P(s){{ return s; }}
const HOODS = {J(hoods)};
const PLACES = {J(keep)};
const WALKS = {J(walks)};
"""
out += (root/'src/static.js').read_text() + '\n' + (root/'src/top.js').read_text()
(root/'src/data.js').write_text(out)
print(f'{len(hoods)} hoods, {len(keep)} places, {len(walks)} walks; dropped (no coords): {dropped}')
